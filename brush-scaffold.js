// Zieht die vom User angesammelten Palette-Eintraege aus dem ALTEN Kopf und haengt sie
// in den neuen ein.
//
// ⚠ Der Kopf ist NICHT nur unser Code — das war ein teurer Irrtum: save_brush.js
// (injectPaletteEntries) und manage_palette.js schreiben Material-Lambdas mitten in das
// `_PHOENIX_PALETTE`-Dict im Kopf. Die erste Fassung dieser Migration ersetzte den Kopf
// samt Dict und hat dabei am 25.07. auf dieser Installation zwei echte Eintraege
// geloescht (StickWood, GlowMat). Alles ueber dem Marker ist also NICHT wegwerfbar.
// Erkannt wird "vom User" daran, dass der Name im frischen SCAFFOLD nicht vorkommt.
// Ist die Zeile fuer sich allein vollstaendig? Klammern zu, Anfuehrungszeichen zu.
// Bewusst ein kleiner Handscanner statt einer Regex: Klammern in Zeichenketten
// ("M_(test)") duerfen nicht mitzaehlen, und genau daran scheitert jede Regex.
function lineIsSelfContained(line) {
  let depth = 0, quote = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quote) {
      if (c === '\\') { i++; continue; }
      if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '#') break;                       // Kommentar bis Zeilenende
    if (c === '(' || c === '[' || c === '{') depth++;
    else if (c === ')' || c === ']' || c === '}') { depth--; if (depth < 0) return false; }
  }
  return depth === 0 && quote === null;
}

function carryPaletteEntries(oldText, newText) {
  const cut = (t) => {
    const open = t.indexOf('_PHOENIX_PALETTE = {');
    const close = open >= 0 ? t.indexOf('\n}', open) : -1;
    return (open < 0 || close < 0) ? null : { open, close, body: t.slice(open, close) };
  };
  const o = cut(oldText), n = cut(newText);
  if (!o || !n) return { text: newText, carried: [] };

  // Name -> Zeilentext des NEUEN Scaffolds. Ein gleichnamiger Eintrag ist nur dann
  // eine Meldung wert, wenn seine Zeile sich unterscheidet — sonst wuerde bei jeder
  // Migration die komplette Standard-Palette als "ersetzt" gemeldet und die Warnung
  // waere nach dem zweiten Mal Rauschen, das niemand mehr liest.
  const knownNew = new Map();
  for (const line of n.body.split(/\r?\n/)) {
    const m = line.match(/^\s*"([^"]+)"\s*:/);
    if (m) knownNew.set(m[1], line.trim());
  }
  const lines = [], names = [], skipped = [], collided = [];
  for (const line of o.body.split(/\r?\n/)) {
    const m = line.match(/^\s*"([^"]+)"\s*:\s*lambda/);
    if (!m) continue;
    if (knownNew.has(m[1])) {
      if (knownNew.get(m[1]) !== line.trim()) collided.push(m[1]);   // vom User veraendert
      continue;
    }
    // Uebernommen wird ZEILENWEISE — ein ueber mehrere Zeilen geschriebener Eintrag
    // wuerde also mitten in der Klammer abgeschnitten und die Datei damit unlesbar
    // machen (jeder Brush tot, nicht nur die Palette). Also nur mitnehmen, was fuer
    // sich allein vollstaendig ist; der Rest bleibt im Backup und wird gemeldet.
    if (!lineIsSelfContained(line)) { skipped.push(m[1]); continue; }
    lines.push(line.replace(/\s+$/, '')); names.push(m[1]);
  }
  if (!lines.length) return { text: newText, carried: [], skipped, collided };
  return {
    text: newText.slice(0, n.close) + '\n' + lines.join('\n') + newText.slice(n.close),
    carried: names, skipped, collided,
  };
}

/**
 * upgradeScaffold — replace an outdated runtime head, keep the user's brushes.
 *
 * Split point is the marker line that save_brush.js appends after: everything BELOW
 * it belongs to the user and is carried over byte-for-byte. The palette entries ABOVE
 * the marker are carried too (see carryPaletteEntries). If the marker is missing the
 * file was hand-edited or predates the convention — then we do NOT touch it, we
 * report. A migration that cannot prove where the user's data starts must not run.
 * Returns {migrated, from, to, backup?, carried?, reason?}.
 */
function upgradeScaffold() {
  let existing;
  try { existing = fs.readFileSync(PY, 'utf8'); } catch (_) { return { migrated: false, reason: 'unreadable' }; }

  const m    = existing.match(VERSION_RE);
  const from = m ? parseInt(m[1], 10) : 1;          // no marker at all = the original, pre-versioning runtime
  if (from >= SCAFFOLD_VERSION) {
    // Aktuelle Version, aber der Marker fehlt: das ist die Signatur einer abgebrochenen
    // Migration (Kopfzeile schon neu, Rest abgeschnitten). Still weitermachen hiesse, den
    // Verlust nie zu bemerken — also laut sagen und auf das Backup zeigen.
    if (existing.indexOf(BRUSH_MARKER) < 0) {
      return { migrated: false, from, to: SCAFFOLD_VERSION, reason: 'version-current-but-truncated' };
    }
    return { migrated: false, from, to: SCAFFOLD_VERSION };
  }

  const idx = existing.indexOf(BRUSH_MARKER);
  if (idx < 0) return { migrated: false, from, to: SCAFFOLD_VERSION, reason: 'marker-missing' };
  const lineEnd = existing.indexOf('\n', idx);
  const tail    = lineEnd >= 0 ? existing.slice(lineEnd + 1) : '';

  // Backup first, and only rewrite if the backup actually landed — losing the user's
  // add_() functions to a half-finished upgrade would be worse than the stale runtime.
  const backup = PY + `.bak-v${from}-${Date.now()}`;
  try {
    fs.writeFileSync(backup, existing, 'utf8');
  } catch (e) {
    return { migrated: false, from, to: SCAFFOLD_VERSION, reason: 'backup-failed: ' + (e.message || e) };
  }
  const fresh = SCAFFOLD.replace('__PHOENIX_LIB_DIR__', LIB_DIR);
  let { text, carried, skipped, collided } = carryPaletteEntries(existing, fresh);

  // Letzte Wache vor dem Umbenennen: ist das Ergebnis als Ganzes noch ausgewogen?
  // Wenn das Uebernehmen die Datei zerbrochen haette, lieber OHNE Palette migrieren
  // als eine unlesbare Datei hinterlassen — die Eintraege liegen dann im Backup.
  const balanced = (t) => {
    const o = t.indexOf('_PHOENIX_PALETTE = {');
    const c = o >= 0 ? t.indexOf('\n}', o) : -1;
    if (o < 0 || c < 0) return false;
    return t.slice(o, c).split(/\r?\n/).every(l => !/^\s*"/.test(l) || lineIsSelfContained(l));
  };
  if (carried.length && !balanced(text)) {
    text = fresh;
    skipped = (skipped || []).concat(carried);
    carried = [];
  }

  // tmp + rename statt direktem Schreiben: stirbt der Prozess mittendrin, bleibt die alte
  // Datei unversehrt stehen. Direkt geschrieben waere sie abgeschnitten — und weil die
  // Versionszeile ganz oben steht, laese der naechste Start sie als "schon aktuell" und
  // wuerde den Verlust nie bemerken. Dasselbe Muster wie in palette.js und blender-ipc.js.
  // Prozess-eigener tmp-Name: bei zwei gleichzeitig migrierenden Prozessen wuerde sonst
  // der zweite rename auf eine bereits weggezogene Datei treffen und der Aufrufer beim
  // Modul-Laden abstuerzen. Fehlschlaege beim Umbenennen sind ein Grund, NICHT zu
  // migrieren — nie ein Grund, die Datei kaputt zu hinterlassen.
  const tmp = PY + '.tmp-' + process.pid;
  try {
    fs.writeFileSync(tmp, text + tail, 'utf8');
    fs.renameSync(tmp, PY);
  } catch (e) {
    try { fs.unlinkSync(tmp); } catch (_) {}
    return { migrated: false, from, to: SCAFFOLD_VERSION, backup, reason: 'write-failed: ' + (e.message || e) };
  }
  return { migrated: true, from, to: SCAFFOLD_VERSION, backup, keptBytes: tail.length, carried, skipped, collided };
}

function ensureBrushScaffold() {
  fs.mkdirSync(LIB_DIR, { recursive: true });
  let scaffold;
  if (!fs.existsSync(PY)) {
    fs.writeFileSync(PY, SCAFFOLD.replace('__PHOENIX_LIB_DIR__', LIB_DIR), 'utf8');
    scaffold = { migrated: false, from: SCAFFOLD_VERSION, to: SCAFFOLD_VERSION, seeded: true };
  } else {
    scaffold = upgradeScaffold();
    if (scaffold.migrated) {
      const pal = (scaffold.carried && scaffold.carried.length)
        ? `, palette kept: ${scaffold.carried.join(', ')}` : '';
      console.log(`  brush runtime upgraded v${scaffold.from} → v${scaffold.to} (your brushes kept${pal}, backup: ${path.basename(scaffold.backup)})`);
      // Was NICHT mitkam, muss genannt werden — sonst meldet die Zeile oben Erfolg,
      // waehrend still etwas fehlt. Genau das war der Fehler dieses Nachmittags.
      if (scaffold.skipped && scaffold.skipped.length) {
        console.warn(`  ⚠ palette entries NOT carried over (spread across several lines — copy them by hand from ${path.basename(scaffold.backup)}): ${scaffold.skipped.join(', ')}`);
      }
      if (scaffold.collided && scaffold.collided.length) {
        console.warn(`  ⚠ your palette entries were replaced by the new built-in ones of the same name: ${scaffold.collided.join(', ')} (your versions are in ${path.basename(scaffold.backup)})`);
      }
    } else if (scaffold.reason === 'version-current-but-truncated') {
      console.warn('  ⚠ phoenix_brushes.py claims the current version but has no brush marker — it looks TRUNCATED. Your brushes may only exist in the newest phoenix_brushes.py.bak-* next to it. Not touching the file.');
    } else if (scaffold.reason === 'marker-missing') {
      console.warn(`  ⚠ brush runtime is v${scaffold.from} (current: v${scaffold.to}) but phoenix_brushes.py has no brush marker — NOT upgraded, leaving it alone. Known bugs of that version stay.`);
    } else if (scaffold.reason) {
      console.warn(`  ⚠ brush runtime upgrade skipped: ${scaffold.reason}`);
    }
  }
  if (!fs.existsSync(REGISTRY)) {
    // RELATIVE, not the absolute PY of the seeding machine: registry.json travels with the
    // brushes/ tree, and use_brush.js resolves it against its own __dirname. An absolute path
    // baked in here is dead the moment the library is copied to another install.
    fs.writeFileSync(REGISTRY, JSON.stringify({ phoenix_source: 'brushes/phoenix_brushes.py', brushes: {} }, null, 2) + '\n', 'utf8');
  }
  return { BRUSHES_DIR, PY, REGISTRY, LIB_DIR, scaffold };
}

module.exports = { ensureBrushScaffold, SCAFFOLD_VERSION };
