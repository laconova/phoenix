/**
 * brush-scaffold.js — seeds the brushes/ scaffold on first use.
 *
 * brushes/ is gitignored (user data: saved .blend libs + the add_() functions that
 * accumulate in phoenix_brushes.py), but the BASE of phoenix_brushes.py and
 * registry.json are CODE the feature needs to exist — without them every fresh
 * clone has a dead brush system. Same self-seed idiom as phoenix-config / palette /
 * workflows ("auto-seeded on first run").
 *
 * _LIB_DIR is baked as an absolute path at seed time because the .py is exec()'d
 * as TEXT inside Blender (no __file__ in that context).
 */

const fs = require('fs');
const path = require('path');

const BRUSHES_DIR = path.join(__dirname, 'brushes');
const PY = path.join(BRUSHES_DIR, 'phoenix_brushes.py');
const REGISTRY = path.join(BRUSHES_DIR, 'registry.json');
const LIB_DIR = path.join(BRUSHES_DIR, 'lib');

const SCAFFOLD = `"""
Phoenix Brush Library — auto-generated by save_brush.js
Do not edit manually. Add brushes via the Phoenix assistant: "save this as a brush called <name>"

Material palette:
  _PHOENIX_PALETTE holds named materials that are shared across all spawned brushes.
  When you spawn multiple brushes that share a material name (e.g. M_Wood_Pine), they
  all reference the same bpy.data.materials entry — edit once, updates everywhere.

  Adding a palette entry:
    _PHOENIX_PALETTE["M_YourMat"] = lambda n: _make_pbr(n, (R, G, B), metallic=X, rough=Y)
  Then call setup_phoenix_palette() at session start to pre-create it.

  If a material is NOT in the palette, _remap_phoenix_materials() still de-duplicates
  .001/.002 copies — so even unnamed materials won't stack up across multiple spawns.
"""
import bpy, os, re

_LIB_DIR = r"__PHOENIX_LIB_DIR__"


# ── Material creators ──────────────────────────────────────────────────────────

def _make_pbr(name, color, metallic=0.0, rough=0.5):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    ns, ls = mat.node_tree.nodes, mat.node_tree.links
    for n in list(ns): ns.remove(n)
    out = ns.new("ShaderNodeOutputMaterial"); out.location = (400, 0)
    b   = ns.new("ShaderNodeBsdfPrincipled"); b.location   = (0, 0)
    b.inputs["Base Color"].default_value = (*color, 1.0)
    b.inputs["Metallic"].default_value   = metallic
    b.inputs["Roughness"].default_value  = rough
    ls.new(b.outputs["BSDF"], out.inputs["Surface"])
    return mat


def _make_emission(name, color, strength=1.0):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    ns, ls = mat.node_tree.nodes, mat.node_tree.links
    for n in list(ns): ns.remove(n)
    out = ns.new("ShaderNodeOutputMaterial"); out.location = (400, 0)
    em  = ns.new("ShaderNodeEmission");       em.location  = (0, 0)
    em.inputs["Color"].default_value    = (*color, 1.0)
    em.inputs["Strength"].default_value = strength
    ls.new(em.outputs["Emission"], out.inputs["Surface"])
    return mat


# ── Shared palette ─────────────────────────────────────────────────────────────
# Starts sparse — entries are added as brushes with named materials accumulate.
# All spawned brushes that reference a palette name share a single material data block.

_PHOENIX_PALETTE = {
    # Wood
    "M_Wood_Pine":   lambda n: _make_pbr(n, (0.52, 0.35, 0.18), metallic=0.0, rough=0.80),
    "M_Wood_Oak":    lambda n: _make_pbr(n, (0.45, 0.28, 0.12), metallic=0.0, rough=0.75),
    "M_Wood_Dark":   lambda n: _make_pbr(n, (0.18, 0.10, 0.05), metallic=0.0, rough=0.85),
    "M_Wood_Worn":   lambda n: _make_pbr(n, (0.38, 0.25, 0.13), metallic=0.0, rough=0.90),
    # Stone / concrete
    "M_Concrete":    lambda n: _make_pbr(n, (0.45, 0.45, 0.43), metallic=0.0, rough=0.90),
    "M_Stone_Grey":  lambda n: _make_pbr(n, (0.40, 0.40, 0.38), metallic=0.0, rough=0.85),
    "M_Brick_Red":   lambda n: _make_pbr(n, (0.55, 0.22, 0.10), metallic=0.0, rough=0.90),
    # Metal
    "M_Metal_Iron":  lambda n: _make_pbr(n, (0.30, 0.30, 0.32), metallic=1.0, rough=0.55),
    "M_Metal_Rust":  lambda n: _make_pbr(n, (0.45, 0.22, 0.10), metallic=0.6, rough=0.85),
    "M_Metal_Copper":lambda n: _make_pbr(n, (0.72, 0.45, 0.20), metallic=1.0, rough=0.30),
    # Generic fallbacks
    "M_White":       lambda n: _make_pbr(n, (0.90, 0.90, 0.90), metallic=0.0, rough=0.60),
    "M_Black":       lambda n: _make_pbr(n, (0.02, 0.02, 0.02), metallic=0.0, rough=0.60),
    "M_DefaultGrey": lambda n: _make_pbr(n, (0.50, 0.50, 0.50), metallic=0.0, rough=0.70),
}


def _mat(name):
    """Get existing palette material by name, or create it. Returns None if unknown."""
    existing = bpy.data.materials.get(name)
    if existing:
        return existing
    creator = _PHOENIX_PALETTE.get(name)
    return creator(name) if creator else None


def setup_phoenix_palette():
    """Pre-create all palette materials in the current scene. Safe to call multiple times."""
    for name in _PHOENIX_PALETTE:
        _mat(name)
        print(f"palette: {name}")
    print("setup_phoenix_palette done")


# ── Material remap ─────────────────────────────────────────────────────────────

def _remap_phoenix_materials(objects):
    """
    Collapse material duplicates (.001, .002 suffixes) to shared palette instances.
    Works for named palette materials AND generic baked materials — any time the same
    base name already exists in bpy.data.materials, the copy is replaced and removed.
    """
    old_mats = set()
    for obj in objects:
        if obj is None or obj.type != 'MESH':
            continue
        for slot in obj.material_slots:
            if slot.material is None:
                continue
            base = re.sub(r'\\.\\d+$', '', slot.material.name)
            shared = _mat(base)
            if shared and shared is not slot.material:
                old_mats.add(slot.material)
                slot.material = shared
    for mat in old_mats:
        if mat.users == 0 and mat.name in bpy.data.materials:
            bpy.data.materials.remove(mat)


# ── Core loader ────────────────────────────────────────────────────────────────

def _load_blend(lib_path, location=(0, 0, 0), instance_name=None):
    """Append all objects from a .blend library file, remap materials, link to scene."""
    with bpy.data.libraries.load(lib_path, link=False) as (data_from, data_to):
        data_to.objects = list(data_from.objects)
    placed_objs = []
    placed = []
    for obj in data_to.objects:
        if obj is not None:
            bpy.context.scene.collection.objects.link(obj)
            obj.location = location
            if instance_name:
                obj.name = instance_name
            placed_objs.append(obj)
            placed.append(obj.name)
    _remap_phoenix_materials(placed_objs)
    return placed


# ── Brushes (appended by save_brush.js) ──────────────────────────────────────
`;

function ensureBrushScaffold() {
  fs.mkdirSync(LIB_DIR, { recursive: true });
  if (!fs.existsSync(PY)) {
    fs.writeFileSync(PY, SCAFFOLD.replace('__PHOENIX_LIB_DIR__', LIB_DIR), 'utf8');
  }
  if (!fs.existsSync(REGISTRY)) {
    fs.writeFileSync(REGISTRY, JSON.stringify({ phoenix_source: PY, brushes: {} }, null, 2) + '\n', 'utf8');
  }
  return { BRUSHES_DIR, PY, REGISTRY, LIB_DIR };
}

module.exports = { ensureBrushScaffold };
