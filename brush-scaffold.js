// phoenix_brushes.py used to be written ONCE ("if it doesn't exist") and never again.
// But it is two things in one file: the RUNTIME at the top (ours, code) and the user's
// saved add_() functions appended below (their data, gitignored). So every fix to the
// runtime reached fresh clones only — an existing install carried the bug forever.
// That is how the 13.07. fixes (oak wearing leaf texture, metre-sized single leaves,
// tree spawning at 1/19 scale) came back in the test copy on 24.07.
//
// Fix: version the runtime. On every entry point, an older file gets its HEAD replaced
// and its TAIL — the user's brushes — appended back unchanged, after a backup.
// Bump SCAFFOLD_VERSION whenever the runtime above changes in a way installs need.
